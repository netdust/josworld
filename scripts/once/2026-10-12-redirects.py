#!/usr/bin/env python3
"""
docs/Jos-redirectlijst-2026-10-12.xlsx (tab Redirects) -> josworld-core/config/legacy-redirects.php.

    python3 scripts/once/2026-10-12-redirects.py

`exact`: old path (lower case, no trailing slash, "" is the home page) -> new URL. `ids`: old WP-ID -> new URL, for
?p=ID and ?page_id=ID. The pattern rules (languages, blog, cases, archives) live in LegacyRedirectService, in the
priority order of the tab Regels. Needs openpyxl. Re-run when the list changes.
"""
import pathlib

import openpyxl

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/Jos-redirectlijst-2026-10-12.xlsx'
TARGET = ROOT / 'app/content/mu-plugins/josworld-core/config/legacy-redirects.php'


def php(value: str) -> str:
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main() -> None:
    sheet = openpyxl.load_workbook(SOURCE)['Redirects']
    exact, ids = {}, {}
    for row in sheet.iter_rows(min_row=8, values_only=True):
        old, new, status, wp_id = row[0], row[1], row[2], row[11]
        if not old:
            continue
        assert status == 301 and str(new).startswith('https://jos.agency/'), row
        key = old.split('?')[0].rstrip('/').lower()
        assert key not in exact or exact[key] == new, (key, new)
        exact[key] = new
        if isinstance(wp_id, int):
            ids[wp_id] = new

    lines = ['<?php', '', '// phpcs:ignoreFile', '', '// Generated by scripts/once/2026-10-12-redirects.py from docs/Jos-redirectlijst-2026-10-12.xlsx. Do not edit.', '',
             'return [', "    'exact' => ["]
    lines += [f"        {php(k)} => {php(v)}," for k, v in sorted(exact.items())]
    lines += ['    ],', "    'ids' => ["]
    lines += [f'        {k} => {php(v)},' for k, v in sorted(ids.items())]
    lines += ['    ],', '];', '']
    TARGET.write_text('\n'.join(lines))
    print(f'{len(exact)} exact paths, {len(ids)} WP-IDs -> {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
